#pragma once

#include <cstddef>
#include <cstring>
#include <fstream>
#include <iostream>

#include "../core/Constants.h"

namespace SpriteHelper {

/**
 * Converts a byte array into a PNG file.
 * Writes the raw bytes from the data array directly to a file.
 * Uses hardcoded default values: fallback red pixel PNG and standard path.
 *
 * @return true if successful, false if file write failed
 */
inline bool BytesArrayToPNG() {
  // Hardcoded fallback PNG: 16x16 red pixel
  static constexpr const unsigned char DATA[] = {
      0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D,
      0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x10,
      0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0xF3, 0xFF, 0x61, 0x00, 0x00, 0x00,
      0x52, 0x49, 0x44, 0x41, 0x54, 0x78, 0x01, 0xDC, 0x90, 0x4B, 0x0A, 0x00,
      0x20, 0x08, 0x44, 0x27, 0xEF, 0x7F, 0x67, 0x53, 0x5C, 0xF8, 0xD9, 0x08,
      0xB5, 0x11, 0x2B, 0x65, 0xE8, 0x81, 0xF0, 0x24, 0x00, 0x1C, 0x8B, 0xC1,
      0x1C, 0x2B, 0x32, 0xCD, 0x91, 0x69, 0xD6, 0x01, 0xF2, 0xFF, 0xFE, 0x06,
      0x0C, 0x10, 0x0F, 0x59, 0x82, 0xF7, 0x83, 0x7C, 0x9D, 0x58, 0xCA, 0xF4,
      0x60, 0x80, 0x02, 0x3E, 0x0F, 0x55, 0x27, 0x33, 0xF5, 0xDE, 0xF1, 0x0D,
      0x3B, 0x70, 0x5B, 0x4B, 0x9D, 0x73, 0xE5, 0x0B, 0x76, 0x70, 0x01, 0x00,
      0x00, 0xFF, 0xFF, 0xAC, 0x7A, 0x51, 0x9F, 0x00, 0x00, 0x00, 0x06, 0x49,
      0x44, 0x41, 0x54, 0x03, 0x00, 0x37, 0x77, 0x50, 0x01, 0x47, 0x9C, 0xB8,
      0x61, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60,
      0x82};

  std::ofstream file(DebugConfig::DEFAULT_SPRITE_PATH,
                     std::ios::binary | std::ios::trunc);
  if (!file.is_open()) {
    std::cerr << "[SpriteHelper::BytesArrayToPNG] Failed to open file: "
              << DebugConfig::DEFAULT_SPRITE_PATH << std::endl;
    return false;
  }

  file.write(reinterpret_cast<const char*>(DATA), sizeof(DATA));

  if (!file) {
    std::cerr << "[SpriteHelper::BytesArrayToPNG] Failed to write to file: "
              << DebugConfig::DEFAULT_SPRITE_PATH << std::endl;
    file.close();
    return false;
  }

  file.close();
  std::cerr << "[SpriteHelper::BytesArrayToPNG] Created PNG: "
            << DebugConfig::DEFAULT_SPRITE_PATH << " (" << sizeof(DATA)
            << " bytes)" << std::endl;
  return true;
}

}  // namespace SpriteHelper
